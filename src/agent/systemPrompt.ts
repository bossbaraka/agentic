/** بناء الـ system prompt النهائي لجلسة معينة */
export function buildSystemPrompt(ctx: {
  mode: BotMode;
  customerName: string;
  customerNumber: string;
  sessionLanguage: string;
  summary: string;
  toolsEnabled: boolean;
}): string {
  const modeBlock =
    ctx.mode === 'business' ? MODE_BUSINESS :
    ctx.mode === 'assistant' ? MODE_ASSISTANT : MODE_HYBRID;

  const vars: Record<string, string> = {
    BOT_NAME: config.bot.BOT_NAME,
    BUSINESS_NAME: config.bot.BUSINESS_NAME,
    MAX_PARTS: String(config.bot.MAX_REPLY_PARTS),
    MAX_CHARS: String(config.bot.MAX_SEGMENT_CHARS),
  };

  const fill = (t: string) => t.replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k] ?? `{{${k}}}`);

  const toolBlock = ctx.toolsEnabled
    ? `
# الأدوات المتاحة (Function Calling)
يمكنك استدعاء الدوال التالية عند الحاجة. لا تستدعِ دالة إلا إذا كانت معطياتها متوفرة أو سألت العميل عنها.
بعد تنفيذ الدالة ستصلك النتيجة؛ اصغِ لها ثم اكتب الرد النهائي بنفس شخصيتك البشرية — لا تلصق أرقامًا جافة، ولا تذكر اسم الدالة للعميل أبدًا.
- get_plan_details: تفاصيل باقة بالأسعار الرسمية (مطلوب: plan_id = starter|pro|enterprise، و billing اختياري = monthly|yearly)
- recommend_plan: توصية بالباقة الأنسب (اختياري: tables، needs)
- capture_subscription_lead: تسجيل طلب تفعيل اشتراك — فقط بعد أن يقرر العميل الاشتراك بوضوح (مطلوب: full_name، restaurant_name، city، tables، preferred_plan، whatsapp_number)
- create_support_ticket: فتح تذكرة دعم لمشترك (مطلوب: restaurant_name، issue، priority = low|normal|high|urgent)
`.trim()
    : '';

  const summaryBlock = ctx.summary
    ? `# ملخص ما سبق في هذه المحادثة\n${ctx.summary}`
    : '# ملخص المحادثة\n(هذه بداية المحادثة أو تم تصفيرها — لا يوجد ملخص سابق.)';

  return fill(`
${modeBlock}

${COMMON_RULES}

# سياق الجلسة الحالية
- اسم العميل في واتساب: ${ctx.customerName || 'غير معروف'}
- رقم العميل: ${ctx.customerNumber}
- لغة المحادثة المعتمدة: ${ctx.sessionLanguage}
- التاريخ والوقت الآن: ${nowHuman()}
- منطقة النشاط الزمنية: Asia/Jerusalem (التزم بها عند ذكر أي موعد أو ساعة عمل)

${summaryBlock}

${toolBlock}

# معلومات النشاط (قاعدة المعرفة)
اعتبر هذه المعلومات هي المصدر الوحيد الموثوق عن النشاط. إن لم تكن الإجابة هنا، فهي غير متوفرة لديك.

${knowledge.render()}

${OUTPUT_CONTRACT}
`.trim());
}

/** prompt مختصر لمهام التلخيص (يستخدم النموذج السريع) */
export function buildSummaryPrompt(existingSummary: string): string {
  return `
أنت ملخّص محادثات. لخص المحادثة التالية في نص عربي مكثّف (أقصى 120 كلمة) يحفظ فقط:
- اسم العميل وأي بيانات تعريفية ذكرها
- ما الذي يريده تحديدًا
- ما الذي تم الاتفاق عليه أو تنفيذه فعلًا
- أي التزامات أو مواعيد معلّقة
- حالة العميل الانفعالية إن كانت لافتة
- الباقة/عدد الطاولات/المدينة إن ذُكرت

لا تضف معلومات غير موجودة. لا تستخدم تعدادًا نقطيًا طويلًا — اكتب فقرة أو نقطتين.

${existingSummary ? `الملخص السابق (ادمجه ولا تكرره):\n${existingSummary}\n` : ''}
`.trim();
}
